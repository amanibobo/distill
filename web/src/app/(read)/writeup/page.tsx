import type { Metadata } from "next";
import { Label, Mono } from "@/components/prose";
import accuracy from "@/data/accuracy.json";
import { CubeSketch, FireSignalSketch, PipelineSketch, RulesSketch, ServingSketch } from "./diagrams";

export const metadata: Metadata = { title: "Writeup · Distill" };

const TYPE_LABEL: Record<string, string> = { flood: "Flood", fire_scar: "Fire scar", harvest: "Harvest", crop_growth: "Crop growth" };
const fmt = (v: number | null) => (v === null ? "n/a" : v.toFixed(2));

type Score = {
  type: string;
  source: string;
  when: string | null;
  pixels: { precision: number | null; recall: number | null; iou: number | null };
  events: { events_scored: number; tp: number; tn: number; fp: number; fn: number; accuracy: number | null };
};
type SiteReport = { site: { id: string; name: string }; passes: number; events: number; scores: Score[] };

const report = accuracy as SiteReport[];

export default function Writeup() {
  const totalEvents = report.reduce((n, s) => n + s.events, 0);
  return (
    <>
      <p className="lede">
        How Distill turns raw NISAR radar into events you can click, and how well it works. Every number on this page is
        generated by the pipeline, not typed in.
      </p>

      <section aria-labelledby="data">
        <Label id="data">the data</Label>
        <p>
          NISAR is an L-band radar satellite built by NASA and ISRO. Calibrated data has been public since 17 June 2026. Distill
          uses the GCOV product, which is radar brightness on a map grid at 10 m, in two polarizations. HH sends and receives
          horizontally, which is good at seeing water and hard surfaces. HV sends horizontally and listens vertically, which picks up
          the volume of leaves and branches. A flood darkens both. A fire or a harvest mostly darkens HV.
        </p>
        <p>
          Each site uses one orbit track, so every pass sees the ground from the same angle. That gives 9 to 12 passes per site,
          twelve days apart.
        </p>
      </section>

      <section aria-labelledby="pipeline">
        <Label id="pipeline">the pipeline</Label>
        <p>
          A GCOV file is about 7 GB, and the laptop this was built on had under 3 GB free. So the pipeline never downloads a file.
          HDF5 stores the image in 512 by 512 tiles, and it reads only the tiles that cover the site over HTTPS, one strip at a
          time. It averages 4 by 4 pixels down to 40 m, which also cuts radar speckle, and caches the result as small files. One
          pass for one site comes to a few megabytes.
        </p>
        <PipelineSketch />
      </section>

      <section aria-labelledby="cube">
        <Label id="cube">events, not snapshots</Label>
        <p>
          Most radar change tools compare two dates. Distill stacks all passes into a cube and segments change in three
          dimensions. Pixels that changed and touch each other in space, or sit on the same spot in neighboring passes, join one
          event. Each event therefore has an onset, a peak, a footprint for every pass and, if it ends, a recovery date.
        </p>
        <CubeSketch />
        <p>
          The time dimension also does work for the labels. A harvest and a flood can look the same in one before and after pair.
          Over a season, one recovers in weeks and the other stays down until spring.
        </p>
      </section>

      <section aria-labelledby="noise">
        <Label id="noise">measuring noise instead of guessing</Label>
        <p>
          The first version used a fixed 3 dB threshold and found 6% of the Kaiser Canyon burn. The fire signal is real but
          small, and one rainy pass shifted the whole scene.
        </p>
        <FireSignalSketch />
        <p>
          Detection now runs in four steps. First it measures change against the median of the pre-event passes. Next it
          subtracts each pass&rsquo;s scene-wide shift, measured only on land that should not change with the seasons, so not
          cropland, water or wetland. Then it smooths over 200 m to find where change is and trims back to pixels whose own change
          agrees. Last, it sets the threshold at three robust standard deviations of the pass-to-pass change between the pre-event
          passes. The reference maps never touch any of this.
        </p>
      </section>

      <section aria-labelledby="rules">
        <Label id="rules">labels with reasons</Label>
        <p>
          Two or three sites are not a training set, so the first labels come from rules a reader can check. The rules look at
          which polarization moved and by how much, the land cover underneath from ESA WorldCover, when the change started, whether
          it grew, and whether it came back.
        </p>
        <RulesSketch />
        <p>
          Claude writes the title and the two or three sentence summary for each event from the same numbers. It sees the rule
          and its reason, the dates, the area and the land cover. It is told not to invent causes or casualties. Its output is
          constrained to a typed schema and cached, so a rerun costs nothing.
        </p>
      </section>

      <section aria-labelledby="accuracy">
        <Label id="accuracy">how well it works</Label>
        <p>
          {totalEvents} events across {report.length} sites, each scored against a map Distill never saw while it was being built.
          Pixel scores ask whether the area labeled with a type matches the reference. Event scores ask whether each event that
          clearly sits inside the reference, or clearly outside it, got the right label.
        </p>
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>Site</th>
                <th>Reference</th>
                <th className="num">Precision</th>
                <th className="num">Recall</th>
                <th className="num">Events right</th>
              </tr>
            </thead>
            <tbody>
              {report.flatMap((s) =>
                s.scores.map((sc) => (
                  <tr key={`${s.site.id}-${sc.type}-${sc.when}`}>
                    <td>
                      {s.site.name}
                      <br />
                      <span style={{ color: "var(--ink-3)" }}>{TYPE_LABEL[sc.type] ?? sc.type}</span>
                    </td>
                    <td>
                      {sc.source}
                      {sc.when ? `, ${sc.when}` : ""}
                    </td>
                    <td className="num">{fmt(sc.pixels.precision)}</td>
                    <td className="num">{fmt(sc.pixels.recall)}</td>
                    <td className="num">
                      {sc.events.tp + sc.events.tn} of {sc.events.events_scored}
                    </td>
                  </tr>
                )),
              )}
            </tbody>
          </table>
        </div>
        <h3>What the numbers do not say</h3>
        <p>
          Fire recall is low because L-band brightness barely changes over burned grass. Interferometric coherence would catch it,
          and that is the next data product to add. Harvest recall is probably inflated because radar also sees crops drying before
          they are cut. The Iowa reference is the 2021 crop map, because the 2025 service was down on the day of the run, and corn
          and soybeans rotate on the same fields. Assam is checked against Sentinel-1 water maps, which share some of radar&rsquo;s
          blind spots.
        </p>
      </section>

      <section aria-labelledby="stack">
        <Label id="stack">serving it</Label>
        <ServingSketch />
        <p>
          The browser never touches radar files. The map asks for one site at a time and gets each event with its footprints, which
          the timeline swaps as you scrub. The grayscale radar under the shapes is one WebP image per pass, reprojected to longitude
          and latitude. The URL holds the site, event, pass and camera, so any view can be shared.
        </p>
        <p>
          Code: the pipeline is Python with <Mono>asf_search</Mono>, <Mono>h5py</Mono>, <Mono>scikit-image</Mono> and{" "}
          <Mono>rasterio</Mono>. The app is Next.js and MapLibre, with events in Postgres and PostGIS. Every decision is logged in the{" "}
          <a href="https://github.com/amanibobo/distill/blob/main/docs/decisions.md">decisions file</a>.
        </p>
      </section>
    </>
  );
}
